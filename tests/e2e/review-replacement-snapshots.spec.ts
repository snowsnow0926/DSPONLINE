import { expect, test } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { gunzipSync } from "node:zlib";

test("rescue replacement requires a verified recovery snapshot before changing the current factory", async ({ page }, testInfo) => {
  test.setTimeout(240_000);
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.addInitScript(() => {
    sessionStorage.setItem("dsp-idle-network.test-bypass-menu", "1");
    if (sessionStorage.getItem("review-replacement-seeded")) return;
    sessionStorage.setItem("review-replacement-seeded", "1");
    localStorage.setItem("dsp-idle-network.release-notes.seen.v1", "2026-11-04-v1.3.7");
    localStorage.setItem("dsp-idle-network.basic-onboarding.v1", JSON.stringify({ version: 1, skipped: true, stepIndex: 5 }));
    localStorage.setItem("dsp-idle-network.save.v1", JSON.stringify({ savedAt: Date.now(), state: {
      version: 47, entities: [], belts: [], construction: {}, tray: { iron_ore: 42 }, paused: true,
      research: { selectedTechId: null, progressByTech: {}, completedTechIds: ["electromagnetism"] },
      blueprints: Array.from({ length: 12 }, (_, index) => ({ id: `original-${index}`, name: `original blueprint ${index}`, revision: 1, rotation: 0, mirror: "none", entities: [{ key: "smelter", buildingId: "arc_smelter", offset: { x: 0, y: 0 }, machineCount: 1, recipeId: "iron_ingot" }], belts: [] })),
      settings: { theme: "dark", fontScale: 1, simulationSpeed: 1, autosaveIntervalSeconds: 0 },
    } }));
  });
  await page.route("**/api/**", (route) => route.fulfill({ status: 503, contentType: "application/json", body: '{"error":"isolated snapshot admission review"}' }));
  await page.goto("/");
  await expect(page.locator(".factory-canvas")).toBeVisible({ timeout: 60_000 });
  await page.getByLabel("打开设置", { exact: true }).click();
  let dialog = page.getByRole("dialog", { name: "运营中心", exact: true });
  await dialog.getByRole("tab", { name: "存档", exact: true }).click();
  const exported = page.waitForEvent("download");
  await dialog.getByRole("button", { name: "导出压缩存档", exact: true }).click();
  const download = await exported;
  const path = await download.path();
  if (!path) throw new Error("Missing original fixture export");
  const bytes = await readFile(path);
  const envelope = JSON.parse((download.suggestedFilename().endsWith(".gz") ? gunzipSync(bytes) : bytes).toString("utf8"));
  expect(envelope.state.tray.iron_ore).toBe(42);
  expect(envelope.state.blueprints).toHaveLength(12);
  expect(envelope.state.settings.autosaveIntervalSeconds).toBe(0);
  envelope.state.tray.iron_ore = 99;
  envelope.state.blueprints = [];
  const damaged = JSON.stringify(envelope);
  await page.evaluate(() => Object.defineProperty(navigator, "storage", { configurable: true, value: { estimate: async () => ({ quota: 1024 * 1024, usage: 1024 * 1024 - (256 * 1024 + 512) }) } }));
  await dialog.getByLabel("选择要导入的存档文件", { exact: true }).setInputFiles({ name: "isolated-damaged.json", mimeType: "application/json", buffer: Buffer.from(damaged) });
  const preview = dialog.getByRole("region", { name: "存档导入预览", exact: true });
  await expect(preview.getByRole("button", { name: "救援此存档", exact: true })).toBeVisible({ timeout: 60_000 });
  await preview.getByRole("button", { name: "救援此存档", exact: true }).click();
  const backup = page.waitForEvent("download");
  await preview.getByRole("button", { name: "再次确认并救援", exact: true }).click();
  expect((await backup).suggestedFilename()).toContain("rescue-backup");
  await expect.poll(async () => (await page.locator(".game-notice").allTextContents()).join(";"), { timeout: 60_000 }).toMatch(/救援完成|快照.*失败/);
  const notice = (await page.locator(".game-notice").allTextContents()).join(";");
  const snapshotCount = await dialog.locator(".save-snapshot-row").filter({ hasText: "救援外部存档前" }).count();
  await testInfo.attach("replacement-snapshot-admission", { body: JSON.stringify({ notice, snapshotCount, errors }), contentType: "application/json" });
  await page.reload();
  await expect(page.locator(".factory-canvas")).toBeVisible({ timeout: 60_000 });
  expect.soft(await page.locator('.tray-row[title="拿取铁矿石"] strong').textContent()).toBe("42");
  expect.soft(notice).toMatch(/快照.*失败/);
  expect(snapshotCount).toBe(0);
  await page.getByLabel("打开设置", { exact: true }).click();
  dialog = page.getByRole("dialog", { name: "运营中心", exact: true });
  await dialog.getByRole("tab", { name: "存档", exact: true }).click();
  const preservedDownload = page.waitForEvent("download");
  await dialog.getByRole("button", { name: "导出压缩存档", exact: true }).click();
  const preservedFile = await preservedDownload;
  const preservedPath = await preservedFile.path();
  if (!preservedPath) throw new Error("Missing preserved fixture export");
  const preservedBytes = await readFile(preservedPath);
  const preserved = JSON.parse((preservedFile.suggestedFilename().endsWith(".gz") ? gunzipSync(preservedBytes) : preservedBytes).toString("utf8"));
  expect(preserved.state.tray.iron_ore).toBe(42);
  expect(preserved.state.blueprints).toHaveLength(12);
  expect(preserved.state.research.completedTechIds).toEqual(["electromagnetism"]);
  expect(preserved.state.settings.autosaveIntervalSeconds).toBe(0);
  await dialog.getByLabel("选择要导入的存档文件", { exact: true }).setInputFiles({ name: "isolated-damaged.json", mimeType: "application/json", buffer: Buffer.from(damaged) });
  const retry = dialog.getByRole("region", { name: "存档导入预览", exact: true });
  await retry.getByRole("button", { name: "救援此存档", exact: true }).click();
  const retryBackup = page.waitForEvent("download");
  await retry.getByRole("button", { name: "再次确认并救援", exact: true }).click();
  expect((await retryBackup).suggestedFilename()).toContain("rescue-backup");
  await expect.poll(async () => (await page.locator(".game-notice").allTextContents()).join(";"), { timeout: 60_000 }).toMatch(/救援完成/);
  await page.getByLabel("打开设置", { exact: true }).click();
  dialog = page.getByRole("dialog", { name: "运营中心", exact: true });
  await dialog.getByRole("tab", { name: "存档", exact: true }).click();
  const recovery = dialog.locator(".save-snapshot-row").filter({ hasText: "救援外部存档前" });
  await expect(recovery).toHaveCount(1);
  await expect(page.locator('.tray-row[title="拿取铁矿石"] strong')).toHaveText("99");
  await recovery.getByRole("button", { name: /^回滚到快照 / }).click();
  await expect(page.locator('.tray-row[title="拿取铁矿石"] strong')).toHaveText("42", { timeout: 60_000 });
  await page.getByLabel("打开设置", { exact: true }).click();
  dialog = page.getByRole("dialog", { name: "运营中心", exact: true });
  await dialog.getByRole("tab", { name: "存档", exact: true }).click();
  const rollbackDownload = page.waitForEvent("download");
  await dialog.getByRole("button", { name: "导出压缩存档", exact: true }).click();
  const rollbackFile = await rollbackDownload;
  const rollbackPath = await rollbackFile.path();
  if (!rollbackPath) throw new Error("Missing rollback fixture export");
  const rollbackBytes = await readFile(rollbackPath);
  const rollback = JSON.parse((rollbackFile.suggestedFilename().endsWith(".gz") ? gunzipSync(rollbackBytes) : rollbackBytes).toString("utf8"));
  expect(rollback.state.blueprints).toHaveLength(12);
  expect(rollback.state.research.completedTechIds).toEqual(["electromagnetism"]);
  expect(rollback.state.settings.autosaveIntervalSeconds).toBe(0);
  expect(errors).toEqual([]);
});
