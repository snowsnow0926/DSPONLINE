function addDefinition(entries: Array<readonly [string, string]>, source: { name: string; description?: string; summary?: string }, englishName: string, kind: "item" | "building" | "technology" | "planet" | "system") {
  entries.push([source.name, englishName]);
  if (source.description) {
    const fallback = kind === "item"
      ? `${englishName} is used in industrial production chains.`
      : kind === "building"
        ? `${englishName} is a production, power, storage, or logistics facility.`
        : kind === "planet"
          ? `${englishName} has a distinct environment and resource profile.`
          : `${englishName} is part of the explorable stellar network.`;
    entries.push([source.description, fallback]);
  }
  if (source.summary) entries.push([source.summary, `${englishName} unlocks related industrial systems and production capabilities.`]);
}

export function registerGameCatalogEnglish(): void {
  const entries: Array<readonly [string, string]> = [];
  for (const [id, definition] of Object.entries(ITEMS)) addDefinition(entries, definition, ITEM_NAMES_EN[id] ?? definition.name, "item");
  for (const [id, definition] of Object.entries(BUILDINGS)) {
    addDefinition(entries, definition, BUILDING_NAMES_EN[id] ?? definition.name, "building");
    if (definition.shortName !== definition.name) {
      entries.push([definition.shortName, BUILDING_SHORT_NAMES_EN[id] ?? BUILDING_NAMES_EN[id] ?? definition.shortName]);
    }
  }
  for (const [id, definition] of Object.entries(RECIPES)) entries.push([definition.name, RECIPE_NAMES_EN[id] ?? ITEM_NAMES_EN[id] ?? definition.name]);
  for (const [id, definition] of Object.entries(TECHNOLOGIES)) {
    addDefinition(entries, definition, TECHNOLOGY_NAMES_EN[id] ?? ITEM_NAMES_EN[id] ?? definition.name, "technology");
    for (const unlock of definition.unlocks) {
      const translation = TECHNOLOGY_UNLOCKS_EN[unlock];
      if (translation) entries.push([unlock, translation]);
    }
  }
  for (const [id, definition] of Object.entries(PLANETS)) {
    addDefinition(entries, definition, PLANET_NAMES_EN[id] ?? definition.name, "planet");
    entries.push([definition.environment, "Distinct planetary environment"]);
    entries.push([definition.resources, definition.resources === "由星区种子生成" ? "Generated from the sector seed" : "Planetary resource deposits"]);
  }
  for (const [id, definition] of Object.entries(STAR_SYSTEMS)) {
    addDefinition(entries, definition, STAR_SYSTEM_NAMES_EN[id] ?? definition.name, "system");
    entries.push([definition.code, STAR_SYSTEM_CODES_EN[id] ?? definition.code]);
  }
  for (const [id, definition] of Object.entries(PLANET_TEMPLATES)) {
    entries.push([definition.name, PLANET_TEMPLATE_NAMES_EN[id] ?? definition.name]);
    entries.push([definition.specializationName, PLANET_SPECIALIZATIONS_EN[definition.specializationName] ?? definition.specializationName]);
  }
  for (const [id, definition] of Object.entries(STAR_CLASS_TEMPLATES)) entries.push([definition.name, STAR_CLASS_NAMES_EN[id] ?? definition.name]);
  for (const chapter of CAMPAIGN_CHAPTERS) {
    const translation = CAMPAIGN_CHAPTERS_EN[chapter.id];
    if (translation) entries.push([chapter.name, translation[0]], [chapter.summary, translation[1]]);
  }
  for (const task of CAMPAIGN_TASKS) {
    const translation = CAMPAIGN_TASKS_EN[task.id];
    if (translation) entries.push([task.title, translation[0]], [task.description, translation[1]]);
  }
  for (const achievement of ACHIEVEMENTS) {
    const translation = ACHIEVEMENTS_EN[achievement.id];
    if (translation) entries.push([achievement.name, translation[0]], [achievement.description, translation[1]]);
  }
  registerCatalogEnglish(entries);
}
